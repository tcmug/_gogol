void test_store_entry_sources_pk_migration() {
    // v3: a store with the legacy (entry_id, toplevel) PK migrates in place on RW
    // open, preserving rows; afterwards two identical-content files in ONE toplevel
    // hold separate entry_sources rows (the old PK silently overwrote the first).
    TEST(store_entry_sources_pk_migration);
    fs::path tmp = fs::temp_directory_path() / ("gogol_esrcmig_" + std::to_string(::getpid()) + ".db");
    fs::remove(tmp); fs::remove(fs::path(tmp.string() + "-wal")); fs::remove(fs::path(tmp.string() + "-shm"));
    std::string id = store::content_id("shared chunk");
    {
        // Legacy v2-shaped cache: entries + entry_sources with the 2-column PK.
        // FTS + triggers are created BEFORE the row insert — a real legacy cache
        // was consistent this way (entries never predate entries_fts), and an
        // external-content FTS 'delete' of a never-indexed row raises CORRUPT.
        Db raw(tmp.string());
        raw.exec("CREATE TABLE entries (id TEXT PRIMARY KEY, content TEXT NOT NULL, embedding BLOB,"
                 " source TEXT, idx TEXT, root_sha TEXT, line INTEGER, end_line INTEGER, symbol TEXT,"
                 " complexity INTEGER, lines INTEGER, params INTEGER, returns INTEGER, max_depth INTEGER)");
        raw.exec("CREATE TABLE entry_sources (entry_id TEXT NOT NULL, toplevel TEXT NOT NULL,"
                 " source TEXT NOT NULL, PRIMARY KEY(entry_id, toplevel),"
                 " FOREIGN KEY(entry_id) REFERENCES entries(id) ON DELETE CASCADE)");
        raw.exec("CREATE TABLE file_hashes (source TEXT PRIMARY KEY, hash INTEGER NOT NULL)");
        raw.exec("CREATE VIRTUAL TABLE entries_fts USING fts5("
                 "  content, symbol, content='entries', content_rowid='rowid')");
        raw.exec("CREATE TRIGGER entries_ai AFTER INSERT ON entries BEGIN"
                 "  INSERT INTO entries_fts(rowid, content, symbol)"
                 "  VALUES (new.rowid, new.content, new.symbol); END;");
        raw.exec("CREATE TRIGGER entries_ad AFTER DELETE ON entries BEGIN"
                 "  INSERT INTO entries_fts(entries_fts, rowid, content, symbol)"
                 "  VALUES ('delete', old.rowid, old.content, old.symbol); END;");
        raw.exec("CREATE TRIGGER entries_au AFTER UPDATE ON entries BEGIN"
                 "  INSERT INTO entries_fts(entries_fts, rowid, content, symbol)"
                 "  VALUES ('delete', old.rowid, old.content, old.symbol);"
                 "  INSERT INTO entries_fts(rowid, content, symbol)"
                 "  VALUES (new.rowid, new.content, new.symbol); END;");
        std::string ins = "INSERT INTO entries (id, content, source, idx) VALUES ('" + id + "', 'shared chunk', '/repo/f.ts', '/repo')";
        raw.exec(ins);
        raw.exec("INSERT INTO entry_sources VALUES ('" + id + "', '/repo', '/repo/f.ts')");
        raw.set_user_version(2);
    }
    {
        store::Store ms(tmp.string()); // RW open: kSchema pass + v3 PK migration
        ms.commit();
        assert(ms.get(id).has_value()); // legacy row survived the migration
        Db raw(tmp.string(), /*read_only=*/true);
        std::string sql;
        {
            Db::Stmt q(raw, "SELECT sql FROM sqlite_master WHERE name='entry_sources'");
            assert(q.step());
            sql = q.column_text(0);
            while (q.step()) {} // drain — else the read tx stays open on a stale snapshot
        }
        assert(sql.find("PRIMARY KEY(entry_id, toplevel, source)") != std::string::npos);
        assert(raw.user_version() == 5);
        // A second identical-content file in the SAME toplevel now coexists.
        store::Store::Loc loc;
        std::string same = ms.put("shared chunk", synth_vec(1), {"/repo"}, "/repo/g.ts", loc, "/repo");
        ms.commit();
        assert(same == id);
        Db::Stmt c(raw, "SELECT COUNT(*) FROM entry_sources WHERE entry_id=?");
        c.bind(1, id);
        assert(c.step());
        assert(c.column_int64(0) == 2); // both files' rows present (old PK kept 1)
    }
    fs::remove(tmp); fs::remove(fs::path(tmp.string() + "-wal")); fs::remove(fs::path(tmp.string() + "-shm"));
    PASS();
}

