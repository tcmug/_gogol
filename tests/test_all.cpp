void test_refresh_budget_stops_and_resumes() {
    // budget stops early + resumes: a deadline in the PAST stops the loop after ~0
    // files (nothing ingested, hit_budget=true); a follow-up refresh with NO budget
    // completes the work. Deterministic (no timing race): past deadline => immediate stop.
    TEST(refresh_budget_stops_and_resumes);
    fs::path root = make_repo("budget");
    std::string dbp = repo_db(root, "cache");
    for (auto s : {std::string("-wal"), std::string("-shm"), std::string("")}) fs::remove(fs::path(dbp+s));
    // Several files so there is real work to leave unfinished.
    for (int i = 0; i < 5; i++)
        std::ofstream(root / ("f" + std::to_string(i) + ".ts")) << "export function f" << i << "() { return " << i << "; }\n";
    CountingEmbedder emb;
    // Deadline already in the past => stop at the FIRST file boundary (before any file).
    auto past = std::chrono::steady_clock::now() - std::chrono::seconds(1);
    {
        store::Store ms(dbp, "");
        auto r = gogol::refresh_repo(ms, emb, root.string(), "", past);
        assert(r.ok);
        assert(r.hit_budget);        // it stopped early
        assert(r.ingested == 0);     // nothing got in (stopped before the first file)
        assert(ms.stats().entries == 0);
        assert(emb.doc_calls == 0);  // no embeds spent
    }
    // Resume with no budget => completes everything left unmarked.
    {
        store::Store ms(dbp, "");
        auto r = gogol::refresh_repo(ms, emb, root.string());  // no deadline
        assert(r.ok);
        assert(!r.hit_budget);
        assert(r.ingested >= 5);                 // all five files now ingested
        assert(ms.stats().entries >= 5);
    }
    // A far-future deadline behaves like no budget (completes in one pass) — proven on
    // a fresh store so we can assert full completion.
    fs::path root2 = make_repo("budget2");
    std::string dbp2 = repo_db(root2, "cache");
    for (auto s : {std::string("-wal"), std::string("-shm"), std::string("")}) fs::remove(fs::path(dbp2+s));
    for (int i = 0; i < 3; i++)
        std::ofstream(root2 / ("g" + std::to_string(i) + ".ts")) << "export function g" << i << "() { return " << i << "; }\n";
    CountingEmbedder emb2;
    auto future = std::chrono::steady_clock::now() + std::chrono::hours(1);
    {
        store::Store ms(dbp2, "");
        auto r = gogol::refresh_repo(ms, emb2, root2.string(), "", future);
        assert(r.ok);
        assert(!r.hit_budget);         // far-future budget never trips
        assert(r.ingested >= 3);
        assert(ms.stats().entries >= 3);
    }
    fs::remove_all(root);
    fs::remove_all(root2);
    PASS();
}

void test_refresh_gc_deleted_files() {
    // GC: a file deleted between refreshes leaves zero rows anywhere (entries,
    // entry_sources, file_hashes, edges, entries_vec) and can no longer surface.
    // A no-deletion refresh purges nothing. A shared-content twin survives GC of
    // its deleted duplicate — the entry stays visible via the surviving source.
    TEST(refresh_gc_deleted_files);
    fs::path root = make_repo("gc");
    std::string dbp = repo_db(root, "cache");
    for (auto s : {std::string("-wal"), std::string("-shm"), std::string("")}) fs::remove(fs::path(dbp+s));
    // gone.ts calls helper (edges file-keyed to gone.ts); twins share identical content.
    std::ofstream(root / "keep.ts")
        << "export function helper() { return 2; }\\n"
        << "export function keeper() { return 2; }\\n";
    std::ofstream(root / "gone.ts")
        << "import { helper } from './keep';\\n"
        << "export function doomed() { return helper(); }\\n";
    std::ofstream(root / "twin1.ts") << "export function twin() { return 3; }\\n";
    std::ofstream(root / "twin2.ts") << "export function twin() { return 3; }\\n";
    CountingEmbedder emb;
    std::string gone_rel = "gone.ts";
    std::string twin1_rel = "twin1.ts";
    std::string twin2_rel = "twin2.ts";
    // Row counters on the raw cache file (each opens a fresh snapshot; drain stmts).
    // NOTE: symbols are NOT asserted here — these one-liner files fall to the window
    // chunker, whose chunks carry no heading (the symbol fallback yields the file
    // extension). Source/id-based rows are the GC contract.
    auto one = [&](const std::string &sql, const std::string &bind) -> int64_t {
        Db raw(dbp, /*read_only=*/true);
        Db::Stmt q(raw, sql);
        q.bind(1, bind);
        int64_t n = q.step() ? q.column_int64(0) : 0;
        while (q.step()) {}
        return n;
    };
    auto scalar = [&](const std::string &sql, const std::string &bind) -> std::string {
        Db raw(dbp, /*read_only=*/true);
        Db::Stmt q(raw, sql);
        q.bind(1, bind);
        std::string s = q.step() ? q.column_text(0) : "";
        while (q.step()) {}
        return s;
    };
    {
        store::Store ms(dbp, "");
        auto r1 = gogol::refresh_repo(ms, emb, root.string());
        assert(r1.ok);
        // idx = the repo's root SHA (identity). file_hashes are keyed by (idx, source).
        std::string IDX; { auto ix = ms.index_locations(); if (!ix.empty()) IDX = ix[0].idx; }
        auto fh_has = [&](const std::string &rel){ return ms.file_hashes(IDX).count(rel); };
        assert(r1.gc_purged == 0);                    // nothing deleted yet
        assert(one("SELECT COUNT(*) FROM entries WHERE source=?", gone_rel) == 1);
        assert(one("SELECT COUNT(*) FROM edges WHERE file=?", gone_rel) >= 1); // call+import edges
        assert(fh_has(gone_rel) == 1);
        std::string doomed_id = scalar("SELECT id FROM entries WHERE source=?", gone_rel);
        // twin1/twin2 have identical SOURCE text but the enriched embed text embeds
        // the filename, so they are DISTINCT entries — each with its own visibility
        // row and its own vec row. (Same-id sharing is a store-API-level case,
        // covered by the entry_sources PK migration test.)
        std::string twin_id = scalar("SELECT id FROM entries WHERE source=?", twin1_rel);
        std::string twin2_id = scalar("SELECT id FROM entries WHERE source=?", twin2_rel);
        assert(!twin_id.empty() && !twin2_id.empty() && twin_id != twin2_id);
        // DELETE gone.ts, refresh: GC must purge every trace of it.
        fs::remove(root / "gone.ts");
        auto r2 = gogol::refresh_repo(ms, emb, root.string());
        assert(r2.ok);
        assert(r2.gc_purged == 1);
        assert(one("SELECT COUNT(*) FROM entries WHERE source=?", gone_rel) == 0);
        assert(one("SELECT COUNT(*) FROM entry_sources WHERE source=?", gone_rel) == 0);
        assert(one("SELECT COUNT(*) FROM edges WHERE file=?", gone_rel) == 0);
        assert(one("SELECT COUNT(*) FROM file_hashes WHERE source=?", gone_rel) == 0);
        assert(one("SELECT COUNT(*) FROM entries_vec WHERE id=?", doomed_id) == 0); // no dead vector
        assert(fh_has(gone_rel) == 0);
        // the twins are untouched by gone.ts's GC
        assert(ms.get(twin_id).has_value());
        assert(ms.get(twin2_id).has_value());
        assert(one("SELECT COUNT(*) FROM entries_vec WHERE id=?", twin2_id) == 1);
        assert(fh_has(twin1_rel) == 1 && fh_has(twin2_rel) == 1);
        // DELETE one twin: only ITS rows go; the sibling file's entry survives.
        fs::remove(root / "twin2.ts");
        auto r3 = gogol::refresh_repo(ms, emb, root.string());
        assert(r3.ok);
        assert(r3.gc_purged == 1);
        assert(ms.get(twin_id).has_value());                     // sibling entry alive
        assert(!ms.get(twin2_id).has_value());                   // deleted twin's entry gone
        assert(one("SELECT COUNT(*) FROM entries_vec WHERE id=?", twin2_id) == 0); // its vec too
        assert(one("SELECT COUNT(*) FROM entry_sources WHERE entry_id=?", twin_id) == 1);
        assert(one("SELECT COUNT(*) FROM entry_sources WHERE source=?", twin2_rel) == 0);
        assert(one("SELECT COUNT(*) FROM entries_vec WHERE id=?", twin_id) == 1); // vec kept (entry alive)
        assert(one("SELECT COUNT(*) FROM entries WHERE source=?", twin2_rel) == 0);
        // A refresh with NO deletions purges nothing (steady state).
        auto r4 = gogol::refresh_repo(ms, emb, root.string());
        assert(r4.ok);
        assert(r4.gc_purged == 0);
    }
    fs::remove_all(root);
    PASS();
}

void test_purge_missing_sources_stat_error_skips() {
    // SC4: a stat ERROR on a candidate path (EACCES on the parent dir, e.g. a
    // dropped mount) must never purge. chmod 000 the parent of an indexed file;
    // purge_missing_sources must skip it. If the test runs with privileges that
    // defeat the chmod (root), exists() succeeds — still no purge; either way
    // the entry must survive. Then restore access, delete the file, and GC runs.
    TEST(purge_missing_sources_stat_error_skips);
    fs::path root = fs::temp_directory_path() / ("gogol_gcperm_" + std::to_string(::getpid()));
    fs::remove_all(root);
    fs::path sub = root / "sub";
    fs::create_directories(sub);
    fs::path dbp = root / "cache.db";
    std::string file_rel = "sub/f.ts";                 // source stored RELATIVE to root
    std::string file_abs = (root / file_rel).string(); // for the stat / fs ops
    {
        store::Store ms(dbp.string(), "");
        std::string id = ms.put("content under lock", synth_vec(1), {"/idx"}, file_rel,
                              store::Store::Loc{}, root.string());
        ms.set_file_hash("/idx", file_rel, 42);
        ms.commit();
        // Lock the parent dir: stat through it fails (EACCES) for unprivileged users.
        fs::permissions(sub, fs::perms::none);
        int64_t purged = ms.purge_missing_sources("/idx", root.string());
        assert(purged == 0);                       // skipped, not purged
        assert(ms.get(id).has_value());             // entry survived
        // Restore access, actually delete the file: now GC purges it.
        fs::permissions(sub, fs::perms::owner_all);
        fs::remove(sub / "f.ts");
        purged = ms.purge_missing_sources("/idx", root.string());
        assert(purged == 1);
        assert(!ms.get(id).has_value());
        assert(ms.file_hashes("/idx").count(file_rel) == 0);
    }
    fs::remove_all(root);
    PASS();
}

