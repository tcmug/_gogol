// looks_like_root_sha: a bare 40/64-hex token is the portable identity a container
// sends. Everything else (paths, bare names, short hex) is not a SHA.
void test_looks_like_root_sha() {
    TEST(looks_like_root_sha);
    assert(gogol::looks_like_root_sha("fe7e0fa59a4abcaca69a0012c19af4c139e266c0"));  // 40 hex
    assert(gogol::looks_like_root_sha(std::string(64, 'a')));                         // 64 hex (sha256)
    assert(!gogol::looks_like_root_sha("fe7e0fa"));                 // too short (abbrev)
    assert(!gogol::looks_like_root_sha("/home/u/tools/gogol"));     // a path
    assert(!gogol::looks_like_root_sha("gogol"));                   // a bare name
    assert(!gogol::looks_like_root_sha("FE7E0FA59A4ABCACA69A0012C19AF4C139E266C0")); // uppercase
    assert(!gogol::looks_like_root_sha(""));
    // 40 chars but a non-hex char (g) -> not a SHA.
    assert(!gogol::looks_like_root_sha("ge7e0fa59a4abcaca69a0012c19af4c139e266c0"));
    PASS();
}

// resolve_scope operates on names/paths. A SHA is a DIFFERENT concept (a portable
// identity for the dedicated `ref` param), not a scope input — so a bare SHA is neither
// a path nor a known repo name and does not resolve (returns nullopt). This is not a
// "rejection": it's simply that a SHA isn't a thing scope matches. (The test name is
// historical — the behavior is "a SHA isn't a scope input", not "scope forbids SHAs".)
void test_resolve_scope_rejects_bare_sha() {
    TEST(resolve_scope_rejects_bare_sha);
    std::vector<gogol::IndexLoc> known = {{"cafe44556677", "/home/u/tools/gogol"}};
    std::string sha = "fe7e0fa59a4abcaca69a0012c19af4c139e266c0";
    // Not a path, not a known repo name, not a path-suffix of any checkout -> unresolved.
    assert(!gogol::resolve_scope(sha, known).has_value());
    assert(!gogol::resolve_scope(sha, {}).has_value());
    PASS();
}

// resolve_recall_scope: a --scope that LOOKS LIKE A PATH (absolute or contains '/') but
// resolves to no indexed repo AND does not exist on disk is an ERROR (RecallScope.error
// set) — like `ls <nonexistent>`, never a silent whole-store union. A BARE NAME miss is
// NOT an error (name lookup legitimately falls through to parent-dir/global).
void test_resolve_recall_scope_rejects_bad_path() {
    TEST(resolve_recall_scope_rejects_bad_path);
    std::vector<gogol::IndexLoc> known = {{"cafe44556677", "/home/u/tools/gogol"}};
    auto mk = [](const std::string& scope) {
        gogol::RecallScopeInputs in; in.scope = scope; in.scope_set = true; return in;
    };
    // Absolute nonexistent path -> error.
    auto r1 = gogol::resolve_recall_scope(mk("/definitely/not/here/xyzzy"), known);
    assert(!r1.error.empty());
    // Relative path-shaped (has '/') nonexistent -> error.
    auto r2 = gogol::resolve_recall_scope(mk("bogus/sub/dir"), known);
    assert(!r2.error.empty());
    // Bare name miss (no '/') -> NOT an error (falls through to parent-dir/global).
    auto r3 = gogol::resolve_recall_scope(mk("nosuchrepo"), known);
    assert(r3.error.empty());
    // A real existing directory (not a repo) -> NOT an error (valid parent-dir union).
    auto r4 = gogol::resolve_recall_scope(mk("/tmp"), known);
    assert(r4.error.empty());
    PASS();
}

// note_scope_matches: the three-shape model. Args are
// (note_scope_id, note_scope_sub, query_ref, query_sub, query_abs).
void test_note_scope_matches_model() {
    TEST(note_scope_matches_model);
    using S = store::Store;
    const std::string R = "fe7e0fa59a4abcaca69a0012c19af4c139e266c0";  // a repo ref
    const std::string R2 = std::string(40, 'b');

    // GLOBAL note (no id, no sub) -> always, whatever the query.
    assert(S::note_scope_matches("", "", R, "src", "/any"));
    assert(S::note_scope_matches("", "", "", "", ""));

    // REPO note, whole repo (id set, sub empty) -> any query in the SAME repo.
    assert(S::note_scope_matches(R, "", R, "", ""));
    assert(S::note_scope_matches(R, "", R, "src/a.ts", ""));   // any subpath in-repo
    assert(!S::note_scope_matches(R, "", R2, "", ""));         // different repo -> no

    // REPO note, subdir (id + relative sub) -> query must be at/under that subdir.
    assert(S::note_scope_matches(R, "services", R, "services", ""));       // exact
    assert(S::note_scope_matches(R, "services", R, "services/products", "")); // under
    assert(!S::note_scope_matches(R, "services", R, "web", ""));           // sibling
    assert(!S::note_scope_matches(R, "services", R, "", ""));              // repo-root query too broad
    assert(!S::note_scope_matches(R, "services", R, "serviceX", ""));      // boundary, not raw prefix
    assert(!S::note_scope_matches(R, "services", R2, "services", ""));     // wrong repo

    // NON-REPO note (no id, ABSOLUTE sub) -> query's absolute path at/under it.
    assert(S::note_scope_matches("", "/work", "", "", "/work"));
    assert(S::note_scope_matches("", "/work", "", "", "/work/web"));
    assert(!S::note_scope_matches("", "/work", "", "", "/other"));
    assert(!S::note_scope_matches("", "/work", "", "", "/workx"));           // boundary
    // a repo query does NOT match a non-repo note (no abs path given).
    assert(!S::note_scope_matches("", "/work", R, "", ""));
    PASS();
}

// resolve_note_scope: a path -> (ref, relative-sub) in a single-root repo, else
// (abs). Runs against THIS checkout (the gogol repo); skips if git is unavailable.
void test_resolve_note_scope() {
    TEST(resolve_note_scope);
    auto gid = gogol::resolve_git_identity("");
    if (!gid || gid->toplevel.empty() || gid->root_sha.empty()) { printf("(skipped) "); PASS(); return; }
    const std::string top = gid->toplevel, sha = gid->root_sha;

    // Repo root -> ref + empty sub.
    { auto ns = gogol::resolve_note_scope(top);
      assert(ns.ref == sha && ns.sub.empty() && ns.abs.empty()); }
    // A subdir of the repo -> ref + relative sub ("src").
    { auto ns = gogol::resolve_note_scope(top + "/src");
      assert(ns.ref == sha && ns.sub == "src" && ns.abs.empty()); }
    // A non-repo absolute dir -> no ref, abs set.
    { auto ns = gogol::resolve_note_scope("/tmp");
      assert(ns.ref.empty() && (ns.abs == "/tmp" || ns.abs == "/private/tmp")); }
    // Empty -> global (all empty).
    { auto ns = gogol::resolve_note_scope("");
      assert(ns.ref.empty() && ns.sub.empty() && ns.abs.empty()); }
    PASS();
}

// ResolvedIdx: the store's index-scoped methods take a ResolvedIdx, which only the
// resolvers can mint from a user string. This is the compile-time guard that makes
// bug d87e3b8 (raw bare name passed to the store -> silent empty) unrepresentable.
// This test asserts the END-TO-END PARITY the type was built to guarantee: a bare
// name and the full path it resolves to produce the SAME store results.
void test_resolved_idx_bare_full_parity() {
    TEST(resolved_idx_bare_full_parity);
    fs::path tmp = fs::temp_directory_path() / ("gogol_ri_" + std::to_string(::getpid()) + ".db");
    fs::remove(tmp); fs::remove(fs::path(tmp.string()+"-wal")); fs::remove(fs::path(tmp.string()+"-shm"));
    {
        store::Store ms(tmp.string());
        // One entry + one edge in an index whose repo_tag is "myrepo".
        const std::string full = "/home/u/proj/myrepo";
        store::Store::Loc loc; loc.line = 1; loc.symbol = "fn";
        ms.put("function fn(){ return other(); }", synth_vec(3), {full}, "src/a.ts", loc);
        ms.add_edge("call", "fn", "other", full);
        ms.commit();
        auto known = ms.index_locations();

        // resolve_scope turns the BARE name into the full idx (ResolvedIdx).
        auto bare_rs = gogol::resolve_scope("myrepo", known);
        assert(bare_rs.has_value() && bare_rs->idx.value() == full);
        auto bare = bare_rs->idx;
        // An already-full path round-trips unchanged.
        auto full_rs = gogol::resolve_scope(full, known);
        assert(full_rs.has_value() && full_rs->idx.value() == full);
        auto full_r = full_rs->idx;
        // A nonexistent name does NOT resolve (resolve_scope returns nullopt) — the old
        // resolve_index wrap-as-is fallback was removed with --index.
        assert(!gogol::resolve_scope("nope", known).has_value());

        // PARITY: bare and full produce identical, non-empty links results. Before the
        // fix, a bare name would have exact-matched the stored full idx -> 0 edges.
        auto via_bare = ms.links("fn", "call", "out", 1, bare);
        auto via_full = ms.links("fn", "call", "out", 1, full_r);
        assert(via_bare.size() == 1 && via_bare[0].dst == "other");
        assert(via_bare.size() == via_full.size());
        // A wrong (resolved) index yields nothing — scoping still bites.
        assert(ms.links("fn", "call", "out", 1,
                        gogol::ResolvedIdx::already_resolved("/home/u/other")).empty());
    }
    fs::remove(tmp); fs::remove(fs::path(tmp.string()+"-wal")); fs::remove(fs::path(tmp.string()+"-shm"));
    PASS();
}

// index_locations + resolve_scope end-to-end for a SHA-keyed index: the regression where
// a bare repo NAME could no longer resolve because entries.idx became the root SHA (so
// repo_tag(idx)==the SHA, never the name). index_locations() pairs the SHA idx with its
// ref_sightings checkout PATH; resolve_scope matches the name against the PATH and
// returns the SHA idx. Guards the exact bug: `--scope <name>` on a SHA-keyed store.
void test_index_locations_sha_name_resolution() {
    TEST(index_locations_sha_name_resolution);
    fs::path tmp = fs::temp_directory_path() / ("gogol_il_" + std::to_string(::getpid()) + ".db");
    fs::remove(tmp); fs::remove(fs::path(tmp.string()+"-wal")); fs::remove(fs::path(tmp.string()+"-shm"));
    {
        store::Store ms(tmp.string());
        // SHA-keyed: idx is a root SHA; the entry is put under that idx, and the repo's
        // on-disk location is recorded as a sighting (what refresh_repo does).
        const std::string sha = "abc123def456abc123def456abc123def456abcd";
        const std::string path = "/home/u/proj/coolrepo";
        store::Store::Loc loc; loc.line = 1; loc.symbol = "fn";
        ms.put("function fn(){ return 1; }", synth_vec(3), {sha}, "src/a.ts", loc, path, sha);
        ms.record_sighting(sha, path);
        ms.commit();

        auto locs = ms.index_locations();
        assert(locs.size() == 1);
        assert(locs[0].idx == sha);          // identity = the SHA
        assert(locs[0].path == path);        // location = the sighting path (NOT the SHA)

        // Bare NAME resolves against the path -> returns the SHA idx (the fix).
        auto rs = gogol::resolve_scope("coolrepo", locs);
        assert(rs.has_value() && rs->idx.value() == sha);
        // Path SUFFIX resolves too.
        auto rs2 = gogol::resolve_scope("proj/coolrepo", locs);
        assert(rs2.has_value() && rs2->idx.value() == sha);
        // The SHA itself is not a scope token (use --ref) -> no name/suffix match.
        assert(!gogol::resolve_scope(sha, locs).has_value());
    }
    fs::remove(tmp); fs::remove(fs::path(tmp.string()+"-wal")); fs::remove(fs::path(tmp.string()+"-shm"));
    PASS();
}

// index_breakdown: per-index identity + entry count + on-disk dir(s), each dir with its
// OWN overlay flag. Guards the status-output contract: (a) root_sha reported ONLY when
// the idx IS a root SHA (a path-keyed idx reports none, even with a stray dedup row
// carrying another repo's SHA), (b) dirs come from ref_sightings for a SHA idx (>1 =
// worktrees) with PER-DIR overlay (one worktree overlay, the other not), (c) a path-keyed
// idx falls back to the idx itself as its dir (never an overlay).
void test_index_breakdown_dirs_and_overlay() {
    TEST(index_breakdown_dirs_and_overlay);
    fs::path tmp = fs::temp_directory_path() / ("gogol_ib_" + std::to_string(::getpid()) + ".db");
    fs::remove(tmp); fs::remove(fs::path(tmp.string()+"-wal")); fs::remove(fs::path(tmp.string()+"-shm"));
    {
        store::Store ms(tmp.string());
        store::Store::Loc loc; loc.line = 1; loc.symbol = "fn";
        // (1) SHA-keyed index seen at TWO checkouts (worktrees); ONLY /co/wt is overlay.
        const std::string sha = "aaaa1111bbbb2222cccc3333dddd4444eeee5555";
        ms.put("function a(){return 1;}", synth_vec(3), {sha}, "src/a.ts", loc, "/co/main", sha);
        ms.record_sighting(sha, "/co/main");
        ms.record_sighting(sha, "/co/wt");
        ms.set_overlay(sha, "/co/wt", true);
        // (2) path-keyed index (multi-root/legacy): idx is a path, root_sha NULL, plus a
        //     stray dedup row carrying a DIFFERENT repo's SHA (the collision bug).
        const std::string pidx = "/home/u/proj/multiroot";
        ms.put("function b(){return 2;}", synth_vec(4), {pidx}, "src/b.ts", loc, pidx);
        ms.put("shared dup content",      synth_vec(5), {pidx}, "src/c.ts", loc, pidx, sha); // stray SHA
        ms.commit();

        // SHA idx: root_sha reported; two dirs; overlay set on /co/wt ONLY.
        store::Store::IndexInfo shaInfo, pInfo;
        for (auto &i : ms.index_breakdown()) {
            if (i.idx == sha)  shaInfo = i;
            if (i.idx == pidx) pInfo = i;
        }
        assert(shaInfo.root_sha == sha);
        assert(shaInfo.dirs.size() == 2);
        bool main_ov = false, wt_ov = false, saw_main = false, saw_wt = false;
        for (auto &d : shaInfo.dirs) {
            if (d.path == "/co/main") { saw_main = true; main_ov = d.overlay; }
            if (d.path == "/co/wt")   { saw_wt = true;   wt_ov = d.overlay; }
        }
        assert(saw_main && saw_wt);
        assert(!main_ov && wt_ov);   // per-dir: main not overlay, wt IS

        // path-keyed idx: NO root_sha despite the stray SHA row; dir = idx, not overlay.
        assert(pInfo.root_sha.empty());
        assert(pInfo.dirs.size() == 1 && pInfo.dirs[0].path == pidx && !pInfo.dirs[0].overlay);
    }
    fs::remove(tmp); fs::remove(fs::path(tmp.string()+"-wal")); fs::remove(fs::path(tmp.string()+"-shm"));
    PASS();
}

