// One JSON-RPC request through the real transport entry point; returns the parsed reply.
static gogol::Json mcp_rpc(const std::string& method, const gogol::Json& params) {
    gogol::Json req = gogol::Json::object();
    req["jsonrpc"] = "2.0";
    req["id"] = 1;
    req["method"] = method;
    req["params"] = params;
    auto raw = gogol::mcp::handle_request_json(req.dump());
    assert(raw.has_value());
    gogol::Json parsed;
    std::string err;
    assert(gogol::json_parse(*raw, parsed, &err));
    return parsed;
}

static std::set<std::string> listed_tools() {
    gogol::Json r = mcp_rpc("tools/list", gogol::Json::object());
    std::set<std::string> names;
    for (const auto& t : r["result"]["tools"]) names.insert(t["name"].get<std::string>());
    return names;
}

static gogol::Json call_tool(const std::string& name, gogol::Json args) {
    gogol::Json p = gogol::Json::object();
    p["name"] = name;
    p["arguments"] = std::move(args);
    return mcp_rpc("tools/call", p);
}

