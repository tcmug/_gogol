void test_store_delete_surface_symmetry() {
    // INVARIANT §1 (docs/INVARIANTS.md): the two delete surfaces must stay symmetric.
    // remove_stale_chunks (CHANGED file) and remove_by_source (DELETED file) both drop
    // entries + entries_vec (vec0 has no cascade); the DELETED-file surface ALSO drops
    // edges (file-keyed) and file_hashes (source-keyed). This test mechanically catches
    // the recurring "satellite reconciled at one site but not the other" regression
    // (bugs 28e1b25 leaked vec rows, 1e8312a dangling edges) that the doc only describes.
    TEST(store_delete_surface_symmetry);
    fs::path tmp = fs::temp_directory_path() / ("gogol_sym_" + std::to_string(::getpid()) + ".db");
    fs::remove(tmp); fs::remove(fs::path(tmp.string()+"-wal")); fs::remove(fs::path(tmp.string()+"-shm"));
    {
        store::Store ms(tmp.string());
        const std::string src = "src/orders.ts";
        // Two chunks of the same file: one we'll KEEP, one that goes STALE.
        store::Store::Loc loc_keep;  loc_keep.line = 1;  loc_keep.symbol = "keepFn";
        store::Store::Loc loc_stale; loc_stale.line = 20; loc_stale.symbol = "staleFn";
        std::string keep_id  = ms.put("function keepFn(){ return 1; }",  synth_vec(1), {"backend"}, src, loc_keep);
        std::string stale_id = ms.put("function staleFn(){ return 2; }", synth_vec(2), {"backend"}, src, loc_stale);
        // Edges + a stat-hash for the file (the file-/source-keyed satellites).
        ms.add_edge("call", "keepFn", "staleFn", "backend", src);
        ms.add_edge("import", src, "src/db.ts", "backend", src);
        ms.set_file_hashes_batch("backend", {{src, 12345u}});
        ms.commit();

        // Baseline: 2 entries, 2 vec rows, 2 edges, 1 file-hash.
        auto s0 = ms.stats();
        assert(s0.entries == 2 && s0.vec_entries == 2 && s0.edges == 2);
        assert(ms.file_hashes("backend").size() == 1);

        // --- CHANGED-file surface: remove_stale_chunks keeps keep_id, drops stale_id.
        int64_t purged = ms.remove_stale_chunks("backend", src, {keep_id});
        ms.commit();
        assert(purged == 1);
        auto s1 = ms.stats();
        // entry AND its vec row both gone (symmetry: no leaked vec row).
        assert(s1.entries == 1 && s1.vec_entries == 1);
        assert(ms.get(keep_id).has_value() && !ms.get(stale_id).has_value());
        // CHANGED-file surface does NOT touch edges or file_hashes (reconciled elsewhere
        // at ingest via remove_edges_of_file) — they survive this call.
        assert(s1.edges == 2 && ms.file_hashes("backend").size() == 1);

        // --- DELETED-file surface: remove_by_source drops the rest + edges + file_hashes.
        int64_t removed = ms.remove_by_source(src);
        ms.commit();
        assert(removed == 1);  // the surviving keep_id entry
        auto s2 = ms.stats();
        // Full symmetry: entries, vec rows, AND edges all gone; file-hash gone too.
        assert(s2.entries == 0 && s2.vec_entries == 0 && s2.edges == 0);
        assert(ms.file_hashes("backend").empty());
    }
    fs::remove(tmp); fs::remove(fs::path(tmp.string()+"-wal")); fs::remove(fs::path(tmp.string()+"-shm"));
    PASS();
}

void test_store_delve_composition() {
    // Covers the composition `delve` performs (both the MCP handle_store_delve and
    // the CLI mem_delve build the SAME structure from these exact store queries):
    //   definition  = ids_for_symbol(symbol) -> get(id)   (its own defining chunk + source)
    //   callers     = links(symbol, "call", "in", 1)
    //   callees     = links(symbol, "call", "out", 1)
    //   imports     = links(def_source, "import", "both", 1)
    // We assert each part is NON-EMPTY and correct — i.e. the deep-dive actually
    // composed a definition + callers + callees + imports, not an empty shell.
    TEST(store_delve_composition);
    fs::path tmp = fs::temp_directory_path() / ("gogol_delve_" + std::to_string(::getpid()) + ".db");
    fs::remove(tmp); fs::remove(fs::path(tmp.string()+"-wal")); fs::remove(fs::path(tmp.string()+"-shm"));
    {
        store::Store ms(tmp.string());
        // A defining entry for processOrder, in source file src/orders.ts, index "backend".
        // Its symbol is stored on the entry row (cache_entries.symbol via the Loc),
        // NOT a separate map (Step 4 collapsed cache_symbols into the column).
        const std::string src = "src/orders.ts";
        store::Store::Loc dloc; dloc.line = 1; dloc.symbol = "processOrder";
        std::string def_id = ms.put("function processOrder(o){ validate(o); return persist(o); }",
                                    synth_vec(7), {"backend"}, src, dloc);
        // Call graph: retryOrder calls processOrder (caller); processOrder calls
        // validate + persist (callees), all in index "backend".
        ms.add_edge("call", "retryOrder", "processOrder", "backend");
        ms.add_edge("call", "processOrder", "validate", "backend");
        ms.add_edge("call", "processOrder", "persist", "backend");
        // Import graph: the defining FILE imports two modules.
        ms.add_edge("import", src, "src/db.ts", "backend");
        ms.add_edge("import", src, "src/validate.ts", "backend");
        ms.commit();

        const std::string symbol = "processOrder";
        const std::string tail = store::symbol_tail(symbol);

        // 1) definition: symbol resolves to its own entry; get() returns source.
        auto ids = ms.ids_for_symbol(tail);
        assert(ids.size() == 1 && ids[0] == def_id);
        auto def = ms.get(ids[0]);
        assert(def.has_value());
        std::string def_source = def->source;
        assert(def_source == src);
        assert(!def->content.empty());

        // 2) callers: in-edges on the call graph -> retryOrder.
        auto callers = ms.links(tail, "call", "in", 1, gogol::ResolvedIdx::already_resolved("backend"));
        assert(callers.size() == 1 && callers[0].src == "retryOrder");

        // 3) callees: out-edges on the call graph -> validate + persist.
        auto callees = ms.links(tail, "call", "out", 1, gogol::ResolvedIdx::already_resolved("backend"));
        assert(callees.size() == 2);
        bool has_validate = false, has_persist = false;
        for (auto &e : callees) { if (e.dst=="validate") has_validate=true; if (e.dst=="persist") has_persist=true; }
        assert(has_validate && has_persist);

        // 4) imports: import edges of the defining file -> db.ts + validate.ts.
        auto imports = ms.links(def_source, "import", "both", 1, gogol::ResolvedIdx::already_resolved("backend"));
        assert(imports.size() == 2);

        // index scoping: a wrong index yields no callers/callees (composition is scoped).
        assert(ms.links(tail, "call", "in", 1, gogol::ResolvedIdx::already_resolved("nope")).empty());
    }
    fs::remove(tmp); fs::remove(fs::path(tmp.string()+"-wal")); fs::remove(fs::path(tmp.string()+"-shm"));
    PASS();
}

