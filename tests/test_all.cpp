// T4: sweep requeues claims past the 1h lease and prunes delivered rows past 30 days.
void test_bus_sweep() {
    TEST(bus_sweep);
    MessageBus bus;
    long t0 = static_cast<long>(std::chrono::duration_cast<std::chrono::seconds>(
        std::chrono::system_clock::now().time_since_epoch()).count());
    int64_t s1 = bus.send("scotty", "kirk", "claimed").seq;
    bus.send("scotty", "kirk", "consumed");
    bus.receive("scotty", 10, true, 300000, "sessA");  // claims s1
    bus.receive("scotty", 10, true);                   // consumes s2 (delivered)
    auto r = bus.sweep(t0 + 10);
    assert(r.requeued == 0 && r.pruned == 0);           // within lease and retention
    r = bus.sweep(t0 + MessageBus::kClaimLease + 10);
    assert(r.requeued == 1 && r.pruned == 0);
    auto got = bus.receive("scotty", 10, true, 300000, "sessA");
    assert(got.messages.size() == 1 && got.messages[0].seq == s1);
    r = bus.sweep(t0 + MessageBus::kDeliveredKeep + 10);
    assert(r.pruned == 1);                              // s2; s1 is claimed, not delivered
    PASS();
}

