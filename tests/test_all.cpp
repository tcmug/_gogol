// repo_tag derives a human-readable label from a git common_dir path (the idx
// stored under the common_dir identity model). The common_dir is typically
// /path/to/repo/.git for a normal repo, or /path/to/repo.git for a bare repo.
void test_repo_tag() {
    TEST(repo_tag);
    // Normal repo: common_dir ends with /.git
    assert(repo_tag("/Users/joe/projects/backend/.git") == "backend");
    assert(repo_tag("/home/u/code/web/.git") == "web");
    // Bare repo: common_dir is /path/to/name.git
    assert(repo_tag("/srv/repos/backend.git") == "backend");
    // Just a path (fallback): take the last component
    assert(repo_tag("/Users/joe/projects/backend") == "backend");
    // Empty input
    assert(repo_tag("").empty());
    PASS();
}

// resolve_git_identity — the worktree-agnostic git-identity resolver, promoted from
// the (now-retired) sg prototype into gogol core (refresh/cmd_store/mcp depend on it).
// Coverage moved here from the deleted tests/test_sg.cpp when sg was retired.
void test_resolve_git_identity_worktree() {
    TEST(resolve_git_identity_worktree);
    fs::path root = fs::temp_directory_path() / ("gogol-test-gid-" + std::to_string(::getpid()));
    fs::remove_all(root);
    std::string repo = (root / "repo").string();
    fs::create_directories(repo + "/sub/deep");
    auto sh = [](const std::string &c) { return system((c + " >/dev/null 2>&1").c_str()); };
    if (sh("git -C '" + repo + "' init") != 0) { fprintf(stderr, "SKIP (no git) "); PASS(); return; }
    sh("git -C '" + repo + "' config user.email t@t");
    sh("git -C '" + repo + "' config user.name t");
    sh("touch '" + repo + "/f.txt'");
    sh("git -C '" + repo + "' add -A");
    sh("git -C '" + repo + "' commit -m init");

    auto main_id = gogol::resolve_git_identity(repo);
    assert(main_id.has_value());
    assert(!main_id->common_dir.empty());
    assert(main_id->prefix == "");                    // at root

    auto sub_id = gogol::resolve_git_identity(repo + "/sub/deep");
    assert(sub_id.has_value());
    assert(sub_id->prefix == "sub/deep/");            // subdir tracked as scope prefix
    assert(sub_id->common_dir == main_id->common_dir);// same repo identity

    // A linked worktree at a DIFFERENT path resolves to the SAME common_dir (the point):
    std::string wt = (root / "wt").string();
    sh("git -C '" + repo + "' worktree add '" + wt + "' HEAD");
    auto wt_id = gogol::resolve_git_identity(wt);
    assert(wt_id.has_value());
    assert(wt_id->common_dir == main_id->common_dir); // worktree = same index identity
    assert(wt_id->toplevel != main_id->toplevel);     // ...but a different checkout path
    fs::remove_all(root);
    PASS();
}

