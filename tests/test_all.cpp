static std::vector<float> synth_vec(unsigned seed) {
    // deterministic pseudo-random unit-ish vector; no model needed in tests.
    std::vector<float> v(store::kDim);
    unsigned s = seed * 2654435761u + 1u;
    for (int i = 0; i < store::kDim; i++) {
        s = s * 1103515245u + 12345u;
        v[i] = ((int)((s >> 8) & 0xFFFF) - 32768) / 32768.0f;
    }
    return v;
}

