// Entries carry a root_sha; scoping a query by the SHA token (as a container does)
// selects that repo's entries via ids_in_indexes matching EITHER idx OR root_sha.
// Regression guard for the source_prefix trap: a SHA is not a path, so it must never
// be used as a checkout (entry_sources.toplevel) restriction — doing so filtered out
// every code/doc entry (no toplevel equals a SHA). Here we pass the SHA as the index
// scope with an EMPTY source_prefix, mirroring the CLI/MCP fix.
void test_store_query_scope_by_root_sha() {
    TEST(store_query_scope_by_root_sha);
    fs::path tmp = fs::temp_directory_path() / ("gogol_sha_" + std::to_string(::getpid()) + ".db");
    fs::remove(tmp); fs::remove(fs::path(tmp.string()+"-wal")); fs::remove(fs::path(tmp.string()+"-shm"));
    {
        store::Store ms(tmp.string());
        const std::string sha  = "fe7e0fa59a4abcaca69a0012c19af4c139e266c0";
        const std::string path = "/home/u/tools/gogol";
        auto va = synth_vec(31), vb = synth_vec(32);
        store::Store::Loc loc;
        // Entry A: belongs to the repo (idx=path, root_sha=sha), recorded in a checkout.
        std::string a = ms.put("repo entry alpha", va, {path}, "/home/u/tools/gogol/a.ts",
                               loc, /*toplevel=*/path, /*root_sha=*/sha);
        // Entry B: a different repo, no matching SHA.
        std::string b = ms.put("other repo entry", vb, {"/other"}, "/other/b.ts",
                               loc, /*toplevel=*/"/other", /*root_sha=*/std::string(40, 'b'));
        ms.commit();

        // Scope by the SHA token, EMPTY source_prefix (container has no host checkout):
        // only repo A's entry comes back.
        auto by_sha = ms.query_hybrid(va, 5, gogol::ResolvedIdx::already_resolved(sha),
                                      /*type=*/"", /*scope_path=*/sha, /*query_text=*/"",
                                      /*source_prefix=*/"");
        bool has_a = false, has_b = false;
        for (auto &h : by_sha) { if (h.id == a) has_a = true; if (h.id == b) has_b = true; }
        assert(has_a && !has_b);

        // Scope by the host PATH still works (idx match), equivalence with the SHA path.
        auto by_path = ms.query_hybrid(va, 5, gogol::ResolvedIdx::already_resolved(path),
                                       "", path, "", /*source_prefix=*/path);
        bool p_has_a = false; for (auto &h : by_path) if (h.id == a) p_has_a = true;
        assert(p_has_a);
    }
    fs::remove(tmp); fs::remove(fs::path(tmp.string()+"-wal")); fs::remove(fs::path(tmp.string()+"-shm"));
    PASS();
}

