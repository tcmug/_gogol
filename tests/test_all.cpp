    fs::path cache = fs::temp_directory_path() / ("gogol_c0_" + std::to_string(::getpid()) + ".db");
    fs::path notes = fs::temp_directory_path() / ("gogol_c0_" + std::to_string(::getpid()) + ".notes.db");
