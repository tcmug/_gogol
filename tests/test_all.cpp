void test_store_fts_rrf_hybrid() {
    // Step 7: query_hybrid is REAL hybrid — cosine + FTS5 keyword, fused via the A3
    // weighted blend (0.6·cosine + 0.4·bm25_norm). A doc that cosine ranks LOW but whose
    // content matches the keyword must surface via the FTS arm; and a pure-semantic
    // query (no keyword hits) still works.
    TEST(store_fts_rrf_hybrid);
    fs::path tmp = fs::temp_directory_path() / ("gogol_fts_" + std::to_string(::getpid()) + ".db");
    fs::remove(tmp); fs::remove(fs::path(tmp.string()+"-wal")); fs::remove(fs::path(tmp.string()+"-shm"));
    {
        store::Store ms(tmp.string());
        // qvec = synth_vec(100). "near" shares that vector (cosine ~1). "kwonly" has a
        // DIFFERENT (near-orthogonal-ish) vector so cosine ranks it low, but its content
        // carries the distinctive keyword "zzytoken".
        auto qv = synth_vec(100);
        std::string near   = ms.put("some nearby content about slots", qv,          {"idx"}, "/r/near.ts");
        std::string kwonly = ms.put("function zzytoken(){ return 0; }", synth_vec(500), {"idx"}, "/r/kw.ts");
        // filler entries so cosine top-k could otherwise crowd out the low-cosine kw hit
        for (int i = 0; i < 8; i++)
            ms.put("filler chunk number " + std::to_string(i), synth_vec(600 + i), {"idx"}, "/r/f" + std::to_string(i) + ".ts");
        ms.commit();

        auto has = [](const std::vector<store::Store::HybridHit> &hits, const std::string &id) {
            for (auto &h : hits) if (h.id == id) return true; return false;
        };
        // FTS table exists.
        {
            Db raw(tmp.string(), /*read_only=*/true);
            Db::Stmt q(raw, "SELECT 1 FROM sqlite_master WHERE name='entries_fts'");
            assert(q.step());
        }
        // keyword_search_scored in isolation resolves the keyword to its entry,
        // and carries the bm25 magnitude the A3 blend consumes.
        auto kw = ms.keyword_search_scored("zzytoken", 5);
        assert(kw.size() == 1 && kw[0].id == kwonly);
        // Hybrid with the keyword: BOTH the cosine winner (near) AND the keyword-only
        // hit (kwonly) surface — the FTS arm contributes a result cosine alone missed.
        auto hyb = ms.query_hybrid(qv, 3, gogol::ResolvedIdx::none(), "", "", "zzytoken");
        assert(has(hyb, near));                    // cosine arm
        assert(has(hyb, kwonly));                   // FTS arm contributed
        // Cosine-only baseline (no query text): the low-cosine kwonly is NOT in top-3,
        // proving the FTS arm is what surfaced it above.
        auto cosine_only = ms.query_hybrid(qv, 3, gogol::ResolvedIdx::none(), "", "", "");
        assert(has(cosine_only, near));             // cosine still works
        assert(!has(cosine_only, kwonly));          // without FTS, kwonly stays buried

        // A3 blend ordering: `near` matches BOTH arms strongly (cosine ~1 for qv, and
        // we query a keyword it also contains), so its blended score must rank it ABOVE
        // the keyword-only hit whose cosine is low. This asserts the magnitude-aware
        // blend, not just presence.
        {
            // Give `near` a keyword the query will also use, so it scores on both arms.
            auto hyb2 = ms.query_hybrid(qv, 5, gogol::ResolvedIdx::none(), "", "", "slots");
            // `near` content contains "slots"; it should be the top hit (both arms).
            assert(!hyb2.empty() && hyb2.front().id == near);
        }
    }
    fs::remove(tmp); fs::remove(fs::path(tmp.string()+"-wal")); fs::remove(fs::path(tmp.string()+"-shm"));
    PASS();
}

