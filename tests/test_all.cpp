// T3: session receive claims; a new session requeues the old one's claims; ack ends it.
void test_bus_session_ack() {
    TEST(bus_session_ack);
    MessageBus bus;
    int64_t s1 = bus.send("scotty", "kirk", "m1").seq;
    auto r = bus.receive("scotty", 10, true, 300000, "sessA");
    assert(r.messages.size() == 1 && r.messages[0].seq == s1);
    // sessA never acked; same session sees nothing more.
    assert(bus.receive("scotty", 10, true, 300000, "sessA").timed_out);
    // A new listen session for scotty requeues sessA's claim: same seq again.
    r = bus.receive("scotty", 10, true, 300000, "sessB");
    assert(r.messages.size() == 1 && r.messages[0].seq == s1);
    assert(bus.ack("scotty", {s1}) == 1);
    // Acked: a further new session gets nothing; neither does a restart requeue.
    assert(bus.requeue_all_claims() == 0);
    assert(bus.receive("scotty", 10, true, 300000, "sessC").timed_out);
    // Unacked claim comes back after a daemon-start requeue.
    int64_t s2 = bus.send("scotty", "kirk", "m2").seq;
    bus.receive("scotty", 10, true, 300000, "sessC");
    assert(bus.requeue_all_claims() == 1);
    r = bus.receive("scotty", 10, true, 300000, "sessC");
    assert(r.messages.size() == 1 && r.messages[0].seq == s2);
    PASS();
}

