// MessageStore (ADR-003): the persistent queue's claim/ack/requeue lifecycle.
void test_message_store_lifecycle() {
    TEST(message_store_lifecycle);
    fs::path p = fs::temp_directory_path() /
                 ("gogol_msg_" + std::to_string(::getpid()) + ".db");
    fs::remove(p);
    fs::remove(p.string() + "-wal");
    fs::remove(p.string() + "-shm");
    int64_t s1 = 0, s2 = 0;
    {
        MessageStore st(p.string());
        s1 = st.enqueue("scotty", "bridge", "one", 100);
        s2 = st.enqueue("scotty", "bridge", "two", 101);
        assert(s2 > s1);
    }
    {
        // SC1: survives close + reopen.
        MessageStore st(p.string());
        assert(st.queued("scotty").size() == 2);

        // SC2: claim without ack, requeue: same seq comes back.
        auto c = st.claim_next("scotty", "sessA", 200);
        assert(c && c->seq == s1 && c->body == "one");
        assert(st.queued("scotty").size() == 1);
        assert(st.requeue_other_sessions("scotty", "sessA") == 0);  // own claim kept
        assert(st.requeue_other_sessions("scotty", "sessB") == 1);
        auto c2 = st.claim_next("scotty", "sessB", 210);
        assert(c2 && c2->seq == s1);
        assert(st.requeue_all() == 1);
        c2 = st.claim_next("scotty", "sessB", 220);
        assert(c2 && c2->seq == s1);

        // SC3: ack => never returned again.
        assert(st.ack("scotty", {s1}, 230) == 1);
        assert(st.ack("scotty", {s1}, 231) == 0);   // idempotent
        assert(st.ack("kirk", {s2}, 231) == 0);     // wrong recipient can't ack
        assert(st.requeue_all() == 0);

        // SC4: empty session = consume-on-receive (delivered at once).
        auto c3 = st.claim_next("scotty", "", 240);
        assert(c3 && c3->seq == s2);
        assert(!st.claim_next("scotty", "", 241));
        assert(st.requeue_all() == 0);

        // SC5: stale claim requeued; old delivered rows pruned.
        int64_t s3 = st.enqueue("scotty", "bridge", "three", 300);
        st.claim_next("scotty", "sessC", 300);
        assert(st.requeue_stale(300) == 0);  // not older than cutoff
        assert(st.requeue_stale(301) == 1);
        assert(st.queued("scotty").size() == 1 && st.queued("scotty")[0].seq == s3);
        assert(st.prune(235) == 1);  // s1 delivered at 230; s2 at 240 stays
        assert(st.prune(1000) == 1);
    }
    {
        // SC6: seq never reused after prune + reopen.
        MessageStore st(p.string());
        int64_t s4 = st.enqueue("scotty", "bridge", "four", 400);
        assert(s4 > s2);
    }
    fs::remove(p);
    fs::remove(p.string() + "-wal");
    fs::remove(p.string() + "-shm");
    PASS();
}

