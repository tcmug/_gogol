// resolve_scope: the unified scoping resolver. Accepts a bare repo name, a path,
// or a path suffix, and returns (idx, toplevel). Matches a name/suffix against each
// index's CHECKOUT PATH (IndexLoc.path) and returns its root-SHA idx — so it works for
// SHA-keyed indexes (idx != path). Tested with synthetic IndexLocs so it needs no store.
void test_resolve_scope_bare_name() {
    TEST(resolve_scope_bare_name);
    // SHA-keyed indexes: idx is a root SHA, the repo name lives in the checkout path.
    std::vector<gogol::IndexLoc> known = {
        {"a1b2c3d4e5f6",                 "/home/u/solo/godot-docs"},
        {"beef00112233",                 "/home/u/solo/godot_sphroam/.git"},
        {"cafe44556677",                 "/home/u/tools/gogol"},
    };
    // Bare name matches repo_tag(PATH) -> returns the SHA idx, path as toplevel.
    auto rs = gogol::resolve_scope("godot-docs", known);
    assert(rs.has_value());
    assert(rs->idx.value() == "a1b2c3d4e5f6");
    assert(rs->toplevel == "/home/u/solo/godot-docs");
    // A checkout path ending in /.git yields a toplevel with /.git stripped.
    auto rs2 = gogol::resolve_scope("godot_sphroam", known);
    assert(rs2.has_value());
    assert(rs2->idx.value() == "beef00112233");
    assert(rs2->toplevel == "/home/u/solo/godot_sphroam");
    PASS();
}

