void test_unix_socket_server() {
    TEST(unix_socket_server);

    std::string sock_path = (fs::temp_directory_path() / ("gogol-socket-" + std::to_string(::getpid()))).string();
    std::thread server([sock_path]() {
        (void)gogol::mcp::run_unix_socket_server(sock_path);
    });
    std::this_thread::sleep_for(std::chrono::milliseconds(150));

    int fd = ::socket(AF_UNIX, SOCK_STREAM, 0);
    assert(fd >= 0);
    sockaddr_un addr{};
    std::memset(&addr, 0, sizeof(addr));
    addr.sun_family = AF_UNIX;
    std::strncpy(addr.sun_path, sock_path.c_str(), sizeof(addr.sun_path) - 1);
    assert(::connect(fd, reinterpret_cast<sockaddr*>(&addr), sizeof(addr)) == 0);

    gogol::Json req = gogol::Json::object();
    req["jsonrpc"] = "2.0";
    req["id"] = 42;
    req["method"] = "tools/list";
    std::string payload = req.dump();
    std::uint32_t len = static_cast<std::uint32_t>(payload.size());
    std::string frame;
    frame.resize(4 + payload.size());
    frame[0] = static_cast<char>((len >> 24) & 0xffu);
    frame[1] = static_cast<char>((len >> 16) & 0xffu);
    frame[2] = static_cast<char>((len >> 8) & 0xffu);
    frame[3] = static_cast<char>(len & 0xffu);
    std::memcpy(frame.data() + 4, payload.data(), payload.size());
    assert(::send(fd, frame.data(), frame.size(), 0) == static_cast<ssize_t>(frame.size()));

    char hdr[4];
    std::size_t got = 0;
    while (got < 4u) {
        ssize_t n = ::recv(fd, hdr + got, 4u - got, 0);
        assert(n > 0);
        got += static_cast<std::size_t>(n);
    }
    std::uint32_t response_len = (static_cast<std::uint32_t>(static_cast<unsigned char>(hdr[0])) << 24) |
                                 (static_cast<std::uint32_t>(static_cast<unsigned char>(hdr[1])) << 16) |
                                 (static_cast<std::uint32_t>(static_cast<unsigned char>(hdr[2])) << 8) |
                                 static_cast<std::uint32_t>(static_cast<unsigned char>(hdr[3]));
    std::string response;
    response.resize(response_len);
    std::size_t off = 0;
    while (off < response_len) {
        ssize_t n = ::recv(fd, response.data() + off, response_len - off, 0);
        assert(n > 0);
        off += static_cast<std::size_t>(n);
    }
    gogol::Json parsed;
    std::string err;
    assert(gogol::json_parse(response, parsed, &err));
    assert(parsed.is_object());
    assert(parsed.contains("result"));
    assert(parsed["result"].is_object());
    assert(parsed["result"].contains("tools"));
    ::close(fd);
    std::remove(sock_path.c_str());
    server.detach();
    PASS();
}


